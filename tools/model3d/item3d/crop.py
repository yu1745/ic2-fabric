def bean(m, x, y, z, w=4.8, h=3.4):
    """咖啡豆：椭圆豆体（两级）+ 正面中缝。"""
    m.box(x, y + 0.4, z, x + w, y + h - 0.4, z + 3.0, mat('#65321d'))
    m.box(x + 0.4, y, z + 0.2, x + w - 0.4, y + h, z + 2.8, mat('#65321d'))
    m.box(x + 0.5, y + 0.5, z + 3.0, x + w - 0.5, y + h - 0.5, z + 3.3, mat('#7c5140'))
    m.box(x + 0.6, y + h / 2 - 0.25, z + 3.3, x + w - 0.6, y + h / 2 + 0.25, z + 3.4, mat('#4c2313'))  # 中缝


