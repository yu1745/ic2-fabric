# ---------------------------------------------------------------- 啤酒花

def hop_cone(m, cx, cy, cz, s=1.0):
    """啤酒花球果：上中下三层叠鳞。"""
    m.box(cx - 1.6 * s, cy - 1.0 * s, cz - 1.6 * s, cx + 1.6 * s, cy + 1.0 * s, cz + 1.6 * s, mat('#bccf11'))
    m.box(cx - 1.1 * s, cy + 1.0 * s, cz - 1.1 * s, cx + 1.1 * s, cy + 1.8 * s, cz + 1.1 * s, mat('#e6ef48'))
    m.box(cx - 1.1 * s, cy - 1.8 * s, cz - 1.1 * s, cx + 1.1 * s, cy - 1.0 * s, cz + 1.1 * s, mat('#99ab07'))
    m.box(cx - 0.9 * s, cy - 0.3 * s, cz + 1.6 * s, cx + 0.9 * s, cy + 0.6 * s, cz + 1.8 * s, mat('#f9ff8d'))  # 高光鳞片


