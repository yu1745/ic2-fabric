@item('terra_wart')
def terra_wart():
    m = Model()
    D, M, L = mat('#16305c'), mat('#2655a6'), mat('#406ebe')
    m.box(4.6, 2.0, 5.6, 11.4, 6.0, 10.4, D)                               # 根块
    for x, y, z, s in ((3.0, 5.4, 6.6, 3.2), (9.6, 6.2, 6.4, 3.4), (6.4, 8.4, 6.8, 3.2),
                       (4.4, 11.0, 7.0, 2.6), (9.4, 10.6, 7.0, 2.6), (7.0, 12.8, 7.2, 2.0)):
        m.box(x, y, z, x + s, y + s, z + s * 0.9, M)                       # 疣瘤
        m.box(x + 0.5, y + s - 0.3, z + 0.4, x + s - 0.5, y + s + 0.3, z + s * 0.9 - 0.4, L)
    m.box(6.8, 2.6, 10.4, 9.4, 4.6, 10.8, mat('#12284e'))
    return m


# ---------------------------------------------------------------- 杂草

@item('weed')
def weed():
    m = Model()
    G1, G2, G3, G4 = mat('#466a26'), mat('#50792b'), mat('#37541e'), mat('#5f9033')
    m.box(5.0, 0.8, 6.6, 11.0, 2.0, 9.4, G3)                               # 根丛
    for x, h, z, t in ((5.4, 9.0, 7.2, G1), (7.4, 13.2, 7.8, G2), (9.2, 10.6, 7.0, G4),
                       (6.4, 6.6, 8.6, G4), (10.2, 7.2, 8.4, G1)):
        m.box(x, 2.0, z, x + 0.9, 2.0 + h, z + 0.8, t)                     # 草茎
    for x0, x1, y, z, t in ((2.4, 5.4, 8.0, 7.2, G2), (8.3, 12.6, 11.6, 7.0, G1), (1.6, 6.4, 5.0, 8.6, G1),
                            (10.2, 14.4, 6.2, 8.4, G2), (3.6, 7.4, 12.4, 7.8, G4), (11.0, 13.6, 9.6, 7.0, G3)):
        m.box(x0, y, z, x1, y + 0.9, z + 0.8, t)                            # 斜伸叶片
        tip = x0 if x0 < 7 else x1 - 0.9
        m.box(tip, y + 0.9, z, tip + 0.9, y + 1.8, z + 0.8, t)             # 叶尖上翘
    return m


