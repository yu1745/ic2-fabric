import math

from core import Model, item, mat

PH = math.pi / 8


def powder_pile(m, base, mid, top, specks=()):
    """粉堆：底盘 → 中层 → 尖顶，逐级收分；specks 为 (x, y, z, 材质) 的表面颗粒。"""
    m.box(1.8, 2.0, 3.8, 14.2, 4.6, 12.2, base)
    m.box(3.2, 4.6, 4.8, 12.8, 7.4, 11.2, mid)
    m.box(4.8, 7.4, 5.8, 11.2, 10.0, 10.2, mid)
    m.box(6.4, 10.0, 6.8, 9.6, 12.0, 9.2, top)
    m.box(7.2, 12.0, 7.4, 8.8, 12.8, 8.6, top)
    for x, y, z, t in specks:
        m.box(x, y, z, x + 1.0, y + 0.8, z + 0.6, t)


